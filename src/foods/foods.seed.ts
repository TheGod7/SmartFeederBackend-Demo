export class FoodsSeed implements OnModuleInit {
  constructor(private readonly prisma: PrismaService) {}

  async onModuleInit(): Promise<void> {
    for (const food of foods) {
      await this.prisma.food.upsert({
        where: { id: `${food.brand}-${food.name}`.toLowerCase().replace(/[^a-z0-9]+/g, '-') },
        update: food,
        create: { id: `${food.brand}-${food.name}`.toLowerCase().replace(/[^a-z0-9]+/g, '-'), ...food },
      });
    }
  }
}
